import json
from typing import Dict, Any, List
from sqlalchemy.orm import Session
from backend.app.models.db_models import Project, Chain, ChainStep, Finding, Asset, Approval, AuditEvent

def generate_sarif_report(project_id: str, db: Session) -> Dict[str, Any]:
    project = db.query(Project).filter(Project.id == project_id).first()
    chains = db.query(Chain).filter(Chain.project_id == project_id).all()

    rules = []
    results = []

    for c in chains:
        rules.append({
            "id": c.id,
            "name": c.title,
            "shortDescription": {"text": f"Attack Chain: {c.title}"},
            "fullDescription": {"text": c.explanation or c.title},
            "defaultConfiguration": {
                "level": "error" if c.severity == "critical" else "warning"
            },
            "properties": {
                "score": c.score,
                "chain_gain": c.chain_gain,
                "likelihood": c.likelihood,
                "impact": c.impact
            }
        })

        results.append({
            "ruleId": c.id,
            "message": {"text": f"High-risk correlated attack path (Score: {c.score}, Gain: +{c.chain_gain}): {c.title}"},
            "level": "error" if c.severity == "critical" else "warning",
            "locations": [
                {
                    "physicalLocation": {
                        "artifactLocation": {"uri": f"assets/{project_id}"},
                        "region": {"startLine": 1}
                    }
                }
            ]
        })

    sarif = {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "ChainedRisk",
                        "version": "1.0.0",
                        "informationUri": "https://github.com/chainedrisk/chainedrisk",
                        "rules": rules
                    }
                },
                "results": results
            }
        ]
    }
    return sarif

def generate_markdown_report(project_id: str, db: Session) -> str:
    project = db.query(Project).filter(Project.id == project_id).first()
    p_name = project.name if project else "Project"
    chains = db.query(Chain).filter(Chain.project_id == project_id).all()
    findings = db.query(Finding).filter(Finding.project_id == project_id).all()
    approvals = db.query(Approval).all()

    md = []
    md.append(f"# ChainedRisk Executive Security Assessment Report")
    md.append(f"**Target Scope:** {p_name} | **Generated by:** ChainedRisk Core Engine\n")
    md.append(f"## 1. Executive Summary")
    md.append(f"- **Raw Findings Ingested:** {len(findings)}")
    md.append(f"- **Correlated Attack Chains:** {len(chains)}")
    reduction = round((1.0 - (len(chains) / max(1, len(findings)))) * 100, 1)
    md.append(f"- **Triage Noise Reduction:** {reduction}%\n")

    md.append(f"## 2. Prioritized Attack Chains")
    for idx, c in enumerate(chains, 1):
        md.append(f"### #{idx}: {c.title}")
        md.append(f"- **Score:** {c.score}/100 (**{c.severity.upper()}**)")
        md.append(f"- **Chain Gain:** +{c.chain_gain} points above highest isolated scanner finding")
        md.append(f"- **Status:** `{c.status}`")
        md.append(f"- **Explanation:** {c.explanation}\n")

        steps = db.query(ChainStep).filter(ChainStep.chain_id == c.id).order_by(ChainStep.ord.asc()).all()
        md.append("| Step | Requires | Provides | Narrative |")
        md.append("|---|---|---|---|")
        for s in steps:
            req = ", ".join(json.loads(s.requires_json or "[]")) or "None"
            prov = ", ".join(json.loads(s.provides_json or "[]")) or "None"
            md.append(f"| {s.ord} | `{req}` | `{prov}` | {s.narrative} |")
        md.append("\n")

    md.append(f"## 3. Human-In-The-Loop Approval & Verification Audit")
    md.append("| Approval ID | Decision | Approver | Justification | Timestamp |")
    md.append("|---|---|---|---|---|")
    for a in approvals:
        md.append(f"| {a.id} | `{a.decision}` | {a.approver} | {a.justification or 'N/A'} | {a.decided_at} |")
    md.append("\n")

    md.append(f"## 4. Remediation Checklist")
    md.append("1. **Block Internal IP Ranges on SSRF Proxy (`/fetch?u=`):** Prevents cross-zone pivot into internal Redis datastores.")
    md.append("2. **Enable Redis Authentication & Bind to Localhost:** Eliminates unauthenticated command execution.")
    md.append("3. **Remove Public Access to `.git` directory:** Eliminates internal infrastructure reconnaissance.")

    return "\n".join(md)

